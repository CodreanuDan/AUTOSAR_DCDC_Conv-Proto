"""HTML report of one coding run (same look as the BZD report). Works without the GUI."""
import html
import os

REPORT_DIR_NAME = "coding_and_parametrisation"


def _hex(b):
    return "" if b is None else " ".join(f"{x:02X}" for x in b)


def report_dir(base_dir):
    return os.path.join(base_dir, REPORT_DIR_NAME, "logs")


def build_html(res, model, project_name=""):
    from ui.bzd_tab import decode_value
    from core.coding_model import OK, DIFF, NODS, ERR, BLOCKED, PENDING
    esc = html.escape
    by = {r.did_txt: r for r in model.rows}

    def ident(did):
        r = by.get(did)
        if r is None:
            return ""
        raw = r.actual if r.actual is not None else r.expected
        return decode_value(r.entry, raw) if raw is not None else ""

    vin = "".join(ident(d) for d in ("F190", "F1A1", "F1A2"))
    cls = {"SUCCESS": "ok", "FAILURE": "bad", "ABORTED": "warn"}[res.status]
    state_txt = {OK: ("OK", "ok"), DIFF: ("DIFFERENT", "bad"), NODS: ("not in dataset", "grey"), ERR: ("ERROR", "bad"),
                 PENDING: ("set by coding", "warn"), BLOCKED: ("not codable - needs flash", "bad")}

    written = "".join(f"<tr><td>{d}</td><td>{esc(n)}</td><td>{esc(o)}</td><td>{esc(v)}</td></tr>" for d, n, o, v in res.written)
    if not written:
        written = "<tr><td colspan='4'>Nothing written</td></tr>"

    mism = "".join(f"<tr><td>{d}</td><td>{esc(n)}</td><td>{esc(e)}</td><td class='bad'>{esc(a)}</td><td>{esc(why)}</td></tr>"
                   for d, n, e, a, why in res.mismatches)
    mism_block = (f"<h2>Mismatches</h2><table><tr><th>DID</th><th>Name</th><th>Expected</th><th>Actual</th><th>Reason</th></tr>{mism}</table>"
                  if mism else "")

    final = ""
    for r in model.rows:
        txt, c = state_txt.get(r.state, ("-", "grey"))
        exp = decode_value(r.entry, r.expected) if r.expected is not None else ""
        act = decode_value(r.entry, r.actual) if r.actual is not None else ""
        final += (f"<tr><td>{r.did_txt}</td><td>{esc(r.name)}</td><td>{esc(exp)}</td><td>{esc(act)}</td>"
                  f"<td class='raw'>{_hex(r.actual)}</td><td class='{c}'>{txt}</td></tr>")

    lvl_cls = {"ok": "ok", "err": "bad", "warn": "warn", "trace": "grey", "info": ""}
    log = "".join(f"<div class='{lvl_cls.get(l, '')}'>[{t}] {esc(x)}</div>" for t, l, x in res.lines if l != "trace")
    trace = "".join(f"<div>[{t}] {esc(x)}</div>" for t, l, x in res.lines if l == "trace")

    return f"""<!doctype html><html><head><meta charset="utf-8"><title>Coding {esc(ident('F187'))} {res.status}</title>
<style>body{{font-family:Segoe UI,Arial,sans-serif;margin:30px;color:#222}}h1{{margin-bottom:0}}h2{{margin-top:26px}}
table{{border-collapse:collapse;margin-top:8px;width:100%}}th,td{{border:1px solid #bbb;padding:5px 9px;text-align:left;font-size:13px}}
th{{background:#e8e8e8}}.raw,.log{{font-family:Consolas,monospace;color:#666}}.ok{{color:#0a7d32;font-weight:bold}}
.bad{{color:#c62828;font-weight:bold}}.warn{{color:#b26a00;font-weight:bold}}.grey{{color:#999}}.meta td{{border:none;padding:2px 14px 2px 0}}
.log div{{font-size:12px;padding:1px 0}}.badge{{display:inline-block;padding:4px 14px;border-radius:4px;color:#fff;font-weight:bold;font-size:18px}}
.badge.ok{{background:#0a7d32}}.badge.bad{{background:#c62828}}.badge.warn{{background:#b26a00}}</style></head><body>
<h1>Coding and parametrisation</h1>
<p>{esc(project_name)}</p>
<p><span class="badge {cls}">{res.status}</span> &nbsp; {esc(res.message)}</p>
<table class="meta">
<tr><td>Started / finished</td><td>{res.started:%Y-%m-%d %H:%M:%S} / {res.finished:%H:%M:%S}</td></tr>
<tr><td>Dataset</td><td>{esc(res.dataset_name)} ({esc(os.path.basename(res.dataset_path))})</td></tr>
<tr><td>Teilenummer</td><td>{esc(ident('F187'))}</td></tr>
<tr><td>Software version</td><td>{esc(ident('F189'))}</td></tr>
<tr><td>Hardware number / version</td><td>{esc(ident('F191'))} / {esc(ident('F193'))}</td></tr>
<tr><td>Serial number</td><td>{esc(ident('F18C'))}</td></tr>
<tr><td>Pseudo-VIN</td><td>{esc(vin)}</td></tr>
<tr><td>Coding status (F1F0)</td><td>{esc(ident('F1F0'))}</td></tr></table>
{mism_block}
<h2>Written values</h2>
<table><tr><th>DID</th><th>Name</th><th>Before</th><th>After (written)</th></tr>{written}</table>
<h2>ECU state at the end</h2>
<table><tr><th>DID</th><th>Name</th><th>Dataset</th><th>ECU</th><th>Raw</th><th>State</th></tr>{final}</table>
<h2>Protocol</h2><div class="log">{log}</div>
<details><summary>UDS frames (TX/RX)</summary><div class="log">{trace}</div></details>
<p style="color:#888;font-size:12px">Generated by DC_DC_Analyzer_Pro.</p>
</body></html>"""


def save_report(res, model, base_dir, project_name=""):
    """Writes the report into <base_dir>/coding_and_parametrisation/logs. Returns the file path."""
    by = {r.did_txt: r for r in model.rows}
    f187 = by.get("F187")
    part = "ECU"
    if f187 is not None:
        raw = f187.actual if f187.actual is not None else f187.expected
        if raw:
            part = raw.decode("ascii", errors="replace").strip() or "ECU"
    ds = "".join(c if c.isalnum() or c in "-_" else "_" for c in res.dataset_name) or "dataset"
    name = f"CODING_{part}_{ds}_{res.started:%Y%m%d_%H%M%S}_{res.status}.html"
    folder = report_dir(base_dir)
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(build_html(res, model, project_name))
    return path